        /// <summary>The largest logo that fits, as lines of VT text; empty if none fits.</summary>
        public static List<string> Render(int maxColumns, int maxRows, bool ascii)
        {
            foreach (string[] pixels in new[] { Pixels56, Pixels40, Pixels28 })
            {
                int rows = (pixels.Length + 1) / 2;
                if (pixels[0].Length <= maxColumns && rows <= maxRows)
                {
                    return ascii ? RenderAscii(pixels) : RenderBlocks(pixels);
                }
            }
            return new List<string>();
        }

        /// <summary>Width in columns of the logo Render would return.</summary>
        public static int Width(int maxColumns, int maxRows)
        {
            foreach (string[] pixels in new[] { Pixels56, Pixels40, Pixels28 })
            {
                if (pixels[0].Length <= maxColumns && (pixels.Length + 1) / 2 <= maxRows)
                {
                    return pixels[0].Length;
                }
            }
            return 0;
        }

        /// <summary>The small badge for the running view's title line: a dark pill with a white 7G.</summary>
        public static void Badge(LineBuilder line, bool ascii)
        {
            if (ascii)
            {
                line.Add("(7G)", Ansi.Bold);
                return;
            }
            string disc = "\x1b[38;2;" + Disc + "m";
            line.Add("▐", disc);
            line.Add("7G", "\x1b[1;38;2;" + Mark + ";48;2;" + Disc + "m");
            line.Add("▌", disc);
        }

        // Each cell shows two vertical pixels: the upper half block takes the top pixel's color as
        // foreground and the bottom pixel's as background.
        private static List<string> RenderBlocks(string[] pixels)
        {
            var lines = new List<string>();
            for (int y = 0; y < pixels.Length; y += 2)
            {
                var text = new StringBuilder();
                for (int x = 0; x < pixels[y].Length; x++)
                {
                    char top = pixels[y][x];
                    char bottom = y + 1 < pixels.Length ? pixels[y + 1][x] : '0';

                    if (top == '0' && bottom == '0')
                    {
                        text.Append(Ansi.Reset).Append(' ');
                    }
                    else if (top == bottom)
                    {
                        text.Append(Ansi.Reset).Append("\x1b[48;2;").Append(Color(top)).Append("m ");
                    }
                    else if (bottom == '0')
                    {
                        text.Append(Ansi.Reset).Append("\x1b[38;2;").Append(Color(top)).Append("m▀");
                    }
                    else if (top == '0')
                    {
                        text.Append(Ansi.Reset).Append("\x1b[38;2;").Append(Color(bottom)).Append("m▄");
                    }
                    else
                    {
                        text.Append(Ansi.Reset).Append("\x1b[38;2;").Append(Color(top)).Append(";48;2;").Append(Color(bottom)).Append("m▀");
                    }
                }
                text.Append(Ansi.Reset);
                lines.Add(text.ToString());
            }
            return lines;
        }

        private static List<string> RenderAscii(string[] pixels)
        {
            var lines = new List<string>();
            for (int y = 0; y < pixels.Length; y += 2)
            {
                var text = new StringBuilder();
                for (int x = 0; x < pixels[y].Length; x++)
                {
                    char top = pixels[y][x];
                    char bottom = y + 1 < pixels.Length ? pixels[y + 1][x] : '0';
                    if (top == '2' || bottom == '2')
                    {
                        text.Append(' ');
                    }
                    else if (top == '1' || bottom == '1')
                    {
                        text.Append('#');
                    }
                    else
                    {
                        text.Append(' ');
                    }
                }
                lines.Add(text.ToString());
            }
            return lines;
        }

        private static string Color(char pixel)
        {
            return pixel == '2' ? Mark : Disc;
        }
